import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

// The words guard (R25.1, R25.2, R25.6): every string literal of src/copy and src/app, and every typeface of src.
const walk = (d: string): string[] => readdirSync(d).flatMap((e) => { const p = join(d, e); return statSync(p).isDirectory() ? walk(p) : [p] })
const isTest = (f: string) => /\.(test|fixture)\.|\/__tests__\//.test(f)
const src = (dir: string) => walk(dir).filter((f) => /\.(ts|tsx)$/.test(f) && !isTest(f))

/** Extracts string literals (', ", ` including the text parts of templates) with a small lexer that skips comments and import lines. */
export function stringLiterals(code: string): string[] {
  const out: string[] = []
  let i = 0
  const n = code.length
  while (i < n) {
    const c = code[i]!
    if (c === '/' && code[i + 1] === '/') { while (i < n && code[i] !== '\n') i++; continue }
    if (c === '/' && code[i + 1] === '*') { const e = code.indexOf('*/', i + 2); i = e < 0 ? n : e + 2; continue }
    if (c === "'" || c === '"') {
      let j = i + 1
      let s = ''
      while (j < n && code[j] !== c && code[j] !== '\n') { if (code[j] === '\\') { s += code[j + 1] ?? ''; j += 2 } else s += code[j++] }
      out.push(s)
      i = j + 1
      continue
    }
    if (c === '`') {
      let j = i + 1
      let s = ''
      while (j < n && code[j] !== '`') {
        if (code[j] === '\\') { s += code[j + 1] ?? ''; j += 2; continue }
        if (code[j] === '$' && code[j + 1] === '{') {
          // the expression inside ${...} is code: scan it too
          let depth = 1
          let k = j + 2
          while (k < n && depth > 0) { if (code[k] === '{') depth++; else if (code[k] === '}') depth--; k++ }
          out.push(...stringLiterals(code.slice(j + 2, k - 1)))
          s += ' '
          j = k
          continue
        }
        s += code[j++]
      }
      out.push(s)
      i = j + 1
      continue
    }
    i++
  }
  return out
}
const withoutImports = (code: string) => code.split('\n').filter((l) => !/^\s*(import\b|export\b.*\bfrom\b)/.test(l)).join('\n')

const FILES = [...src('src/copy'), ...src('src/app')]
const literals = FILES.flatMap((f) => stringLiterals(withoutImports(readFileSync(f, 'utf8'))).map((s) => ({ f, s })))
const unlike = (s: string) => s.replace('Her Hand in the Steam', '')

describe('the words guard (R25.1)', () => {
  it('scans real files', () => {
    expect(FILES.length).toBeGreaterThan(1)
    expect(literals.length).toBeGreaterThan(40)
  })
  it('the lexer reads quotes, templates and comments', () => {
    expect(stringLiterals(`const a = 'x "y"' // 'no'\nconst b = \`t \${f('in')} u\` /* "no" */`)).toEqual(['x "y"', 'in', 't   u'])
  })
  it.each(['she', 'her', 'hers'])('no string literal contains the word "%s" (except in the product title)', (w) => {
    const re = new RegExp(`\\b${w}\\b`, 'i')
    expect(literals.filter(({ s }) => re.test(unlike(s))).map((x) => `${x.f}: ${x.s}`)).toEqual([])
  })
  it.each(['curator', 'AI-powered', 'Kiro-powered', 'generated by', 'enhanced', 'restored', 'chatbot', 'assistant'])('no string literal contains "%s"', (w) => {
    expect(literals.filter(({ s }) => s.toLowerCase().includes(w.toLowerCase())).map((x) => `${x.f}: ${x.s}`)).toEqual([])
  })
  it('no digit anywhere in a string literal, except in "×4" and "×12"', () => {
    const bad = literals.filter(({ s }) => /\d/.test(s.replaceAll('×12', '').replaceAll('×4', '')))
    expect(bad.map((x) => `${x.f}: ${x.s}`)).toEqual([])
  })
})

describe('no speech and no handwriting face (R25.6, R16.3)', () => {
  const ALL = walk('src').filter((f) => /\.(ts|tsx|css)$/.test(f) && !isTest(f) && !f.endsWith('strings.test.ts'))
  it('never names speechSynthesis or SpeechSynthesisUtterance', () => {
    expect(ALL.filter((f) => /speechSynthesis|SpeechSynthesisUtterance/.test(readFileSync(f, 'utf8')))).toEqual([])
  })
  it('names no handwriting-style font-family', () => {
    const hand = /(cursive|handwrit|segoe script|bradley hand|comic|caveat|dancing script|brush script|lucida hand|zapfino|snell|pacifico|kalam|patrick hand|indie flower|shadows into light|reenie)/i
    const hits = ALL.flatMap((f) => (readFileSync(f, 'utf8').match(/font-family\s*:[^;}]*/gi) ?? []).filter((m) => hand.test(m)).map((m) => `${f}: ${m}`))
    expect(hits).toEqual([])
  })
})
